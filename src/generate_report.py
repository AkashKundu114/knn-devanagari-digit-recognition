"""Generate LaTeX data macros/tables from results/ and compile report/assignment_report.pdf."""
from __future__ import annotations

import json
from pathlib import Path
import shutil
import subprocess

import pandas as pd

REPO_ROOT = Path(__file__).resolve().parents[1]


def _find_pdflatex() -> str | None:
    """Locate pdflatex on PATH or in standard Windows MiKTeX install path."""
    found = shutil.which("pdflatex")
    if found:
        return found
    miktex_candidate = (
        Path.home()
        / "AppData"
        / "Local"
        / "Programs"
        / "MiKTeX"
        / "miktex"
        / "bin"
        / "x64"
        / "pdflatex.exe"
    )
    if miktex_candidate.is_file():
        return str(miktex_candidate)
    return None


def write_latex_results(
    results_dir: Path = Path("results"),
    latex_dir: Path = Path("report/latex"),
) -> Path:
    """Populate report/latex/generated_results.tex and figures/ from actual experiment outputs."""
    metrics = json.loads((results_dir / "metrics.json").read_text(encoding="utf-8"))
    inspection = json.loads((results_dir / "dataset_inspection.json").read_text(encoding="utf-8"))
    k_comp = pd.read_csv(results_dir / "k_comparison.csv")
    preds = pd.read_csv(results_dir / "sample_predictions.csv")

    figures_dir = latex_dir / "figures"
    figures_dir.mkdir(parents=True, exist_ok=True)
    for fig_name in ("confusion_matrix.png", "dataset_samples.png", "k_validation_curve.png", "class_distribution.png"):
        src_fig = results_dir / fig_name
        if src_fig.is_file():
            shutil.copy2(src_fig, figures_dir / fig_name)

    piv = k_comp.pivot(
        index=["preprocess_mode", "image_size", "feature_count", "weights"],
        columns="k",
        values="validation_accuracy",
    )
    best_mode = metrics["selected_preprocess_mode"]
    best_size = int(metrics["image_size"])
    best_weights = metrics["weights"]
    best_k = int(metrics["selected_k"])

    table_lines = []
    for (mode, size, feats, weight), row in piv.iterrows():
        cells = []
        for k_val in (1, 3, 5, 7, 9):
            if k_val not in row.index or pd.isna(row[k_val]):
                cells.append("--")
                continue
            val_str = f"{row[k_val] * 100:.2f}"
            if mode == best_mode and int(size) == best_size and weight == best_weights and k_val == best_k:
                cells.append(f"\\textbf{{{val_str}}}")
            else:
                cells.append(val_str)
        table_lines.append(
            f"    {mode} & {int(size)}$\\times${int(size)} ({int(feats)}) & {weight} & "
            + " & ".join(cells)
            + " \\\\"
        )

    raw_rows = k_comp[k_comp["preprocess_mode"] == "raw"]
    best_raw_val = float(raw_rows["validation_accuracy"].max()) if not raw_rows.empty else 0.0

    counts_summary = ", ".join(
        f"{d}:{inspection['unique_class_counts'][str(d)]}" for d in range(10)
    )
    env = metrics["environment"]
    sc = metrics["split_counts"]
    correct_count = int(preds["correct"].sum())
    error_count = int((~preds["correct"]).sum())

    tex_content = "\n".join([
        "% Auto-generated by src/generate_report.py from results/metrics.json",
        f"\\newcommand{{\\TotalRawRows}}{{{inspection['raw_digit_images']:,}}}",
        f"\\newcommand{{\\DuplicatesRemoved}}{{{inspection['duplicates_removed']:,}}}",
        f"\\newcommand{{\\TotalUniqueImages}}{{{inspection['unique_digit_images']:,}}}",
        f"\\newcommand{{\\TotalCharRows}}{{{inspection['excluded_alphabet_subset'].get('rows', 0):,}}}",
        f"\\newcommand{{\\DigitCountsSummary}}{{{counts_summary}}}",
        f"\\newcommand{{\\TrainCount}}{{{sc['train']}}}",
        f"\\newcommand{{\\ValCount}}{{{sc['validation']}}}",
        f"\\newcommand{{\\RefitCount}}{{{sc['final_training_after_refit']}}}",
        f"\\newcommand{{\\TestCount}}{{{sc['test']}}}",
        f"\\newcommand{{\\SelectedMode}}{{{best_mode}}}",
        f"\\newcommand{{\\SelectedSize}}{{{best_size}}}",
        f"\\newcommand{{\\SelectedK}}{{{best_k}}}",
        f"\\newcommand{{\\SelectedWeights}}{{{best_weights}}}",
        f"\\newcommand{{\\ValAccPct}}{{{metrics['selected_validation_accuracy'] * 100:.2f}\\%}}",
        f"\\newcommand{{\\BestRawValPct}}{{{best_raw_val * 100:.2f}\\%}}",
        f"\\newcommand{{\\TestAccPct}}{{{metrics['test_accuracy'] * 100:.2f}\\%}}",
        f"\\newcommand{{\\MacroPrecPct}}{{{metrics['test_macro_precision'] * 100:.2f}\\%}}",
        f"\\newcommand{{\\MacroRecPct}}{{{metrics['test_macro_recall'] * 100:.2f}\\%}}",
        f"\\newcommand{{\\MacroFonePct}}{{{metrics['test_macro_f1'] * 100:.2f}\\%}}",
        f"\\newcommand{{\\CorrectCount}}{{{correct_count}}}",
        f"\\newcommand{{\\ErrorCount}}{{{error_count}}}",
        f"\\newcommand{{\\PythonVersion}}{{{env['python_version']}}}",
        f"\\newcommand{{\\NumpyVersion}}{{{env['numpy_version']}}}",
        f"\\newcommand{{\\PandasVersion}}{{{env['pandas_version']}}}",
        f"\\newcommand{{\\PillowVersion}}{{{env['pillow_version']}}}",
        f"\\newcommand{{\\SklearnVersion}}{{{env['scikit_learn_version']}}}",
        f"\\newcommand{{\\MatplotlibVersion}}{{{env['matplotlib_version']}}}",
        "\\newcommand{\\ValidationComparisonRows}{%",
        *table_lines,
        "}",
        "",
    ])

    out_tex = latex_dir / "generated_results.tex"
    out_tex.write_text(tex_content, encoding="utf-8")
    return out_tex


def compile_latex_pdf(
    latex_dir: Path = Path("report/latex"),
    output_pdf: Path = Path("report/assignment_report.pdf"),
) -> Path:
    """Compile report/latex/main.tex into report/assignment_report.pdf via pdflatex."""
    pdflatex = _find_pdflatex()
    if pdflatex is None:
        raise RuntimeError(
            "pdflatex was not found on PATH. Install MiKTeX or TeX Live and run: "
            "cd report/latex && pdflatex main.tex && pdflatex main.tex"
        )

    cmd = [pdflatex, "-interaction=nonstopmode", "-halt-on-error"]
    if "miktex" in pdflatex.lower():
        cmd.append("--disable-installer")
    cmd.append("main.tex")
    for _ in range(2):
        proc = subprocess.run(
            cmd,
            cwd=str(latex_dir),
            stdin=subprocess.DEVNULL,
            capture_output=True,
            text=True,
            timeout=60,
            check=False,
        )
        if proc.returncode != 0:
            raise RuntimeError(
                f"pdflatex failed with exit code {proc.returncode}:\n{proc.stdout}\n{proc.stderr}"
            )

    built_pdf = latex_dir / "main.pdf"
    if not built_pdf.is_file():
        raise FileNotFoundError(f"Expected compiled PDF at {built_pdf}")
    output_pdf.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(built_pdf, output_pdf)

    for ext in (".aux", ".log", ".out", ".pdf"):
        aux_file = latex_dir / f"main{ext}"
        if aux_file.exists():
            aux_file.unlink()
    return output_pdf


def build_pdf_report(
    results_dir: Path = Path("results"),
    latex_dir: Path = Path("report/latex"),
    output_pdf: Path = Path("report/assignment_report.pdf"),
) -> Path:
    """Populate LaTeX results and compile the assignment PDF."""
    write_latex_results(results_dir=results_dir, latex_dir=latex_dir)
    return compile_latex_pdf(latex_dir=latex_dir, output_pdf=output_pdf)


if __name__ == "__main__":
    pdf_path = build_pdf_report()
    print(f"Generated LaTeX PDF report at: {pdf_path.resolve()} ({pdf_path.stat().st_size} bytes)")
